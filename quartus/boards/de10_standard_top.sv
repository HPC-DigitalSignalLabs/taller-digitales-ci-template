// Board-level top wrapper for the Terasic DE10-Standard (Intel Cyclone V SX
// 5CSXFC6D6F31C6). Analogous to de1_soc_top.sv: it maps the maintained
// reference design `counter` onto the DE10-Standard top-level ports.
//
// ============================ UNVERIFIED (BL-011) ============================
// The DE10-Standard physical PIN ASSIGNMENTS in quartus/de10_standard.qsf are
// NOT yet verified against the official Terasic DE10-Standard user manual. Both
// boards share the Cyclone V SoC family, USB-Blaster II, a 50 MHz fabric clock
// and a comparable teaching panel (10 switches, 10 red LEDs, six HEX displays),
// so the LOGICAL interface below is expected to match. The exact pin locations
// and IO standards MUST be confirmed against the manual before compiling a
// production bitstream. See docs/decisions/backlog.md (BL-011) and ADR-0008.
// =============================================================================
//
// Course-maintained reference material (analogous to lib/). To customise the
// panel mapping for an exercise, copy this file into src/ and re-point
// TOP_LEVEL_ENTITY; do not edit this file in place.
//
// Convention notes (same as DE1-SoC, pending manual verification):
//   * KEY[*] are assumed active-low push buttons; KEY[0] drives rst_n directly.
//   * SW[0] is the count enable.
//   * The 8-bit count drives LEDR[7:0]; LEDR[9:8] are tied off.

`timescale 1ns/1ps
`default_nettype none

module de10_standard_top (
    input  wire        CLOCK_50,   // 50 MHz fabric clock (pin UNVERIFIED, BL-011)
    input  wire [3:0]  KEY,        // active-low push buttons (assumed)
    input  wire [9:0]  SW,         // slide switches
    output wire [9:0]  LEDR,       // red LEDs
    output wire [6:0]  HEX0,       // seven-segment displays (active-low segments)
    output wire [6:0]  HEX1,
    output wire [6:0]  HEX2,
    output wire [6:0]  HEX3,
    output wire [6:0]  HEX4,
    output wire [6:0]  HEX5
);

  localparam int unsigned WIDTH = 8;

  logic [WIDTH-1:0] count;

  counter #(
      .WIDTH(WIDTH)
  ) u_counter (
      .clk    (CLOCK_50),
      .rst_n  (KEY[0]),
      .enable (SW[0]),
      .count  (count)
  );

  assign LEDR = {2'b00, count};

  // Reuses the shared active-low seven-segment decoder (quartus/boards/seg7_hex.sv).
  seg7_hex u_hex0 (.nibble(count[3:0]), .seg(HEX0));
  seg7_hex u_hex1 (.nibble(count[7:4]), .seg(HEX1));

  assign HEX2 = 7'h7F;
  assign HEX3 = 7'h7F;
  assign HEX4 = 7'h7F;
  assign HEX5 = 7'h7F;

endmodule

`default_nettype wire
