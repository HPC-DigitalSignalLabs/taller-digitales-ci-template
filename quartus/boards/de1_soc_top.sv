// Board-level top wrapper for the Terasic DE1-SoC (Intel Cyclone V
// 5CSEMA5F31C6). It maps the maintained reference design `counter` onto the
// physical top-level ports the DE1-SoC exposes, so a student can open the
// committed Quartus project (quartus/de1_soc.qsf) and compile a real bitstream
// without wiring anything by hand.
//
// This is COURSE-MAINTAINED REFERENCE material, analogous to lib/. A student
// who needs a different panel mapping should copy this file into their own
// board top under src/ and point TOP_LEVEL_ENTITY at it; do not edit this file
// in place for a specific exercise.
//
// Port names, widths and pin assignments are board-specific (see ADR-0008).
// The physical pin/IO-standard map lives in quartus/de1_soc.qsf and follows the
// canonical Terasic DE1-SoC SystemBuilder pin table; confirm it against your
// board's user manual before a production bitstream.
//
// Convention notes:
//   * KEY[*] are active-low push buttons: pressed drives 0. KEY[0] is used
//     directly as the counter's active-low reset (rst_n), so pressing KEY[0]
//     resets the design -- no inversion required.
//   * SW[0] is the count enable.
//   * The 8-bit count drives LEDR[7:0]; LEDR[9:8] are tied off. The low and
//     high nibbles are also shown on HEX0/HEX1 as a simple visual aid.

`timescale 1ns/1ps
`default_nettype none

module de1_soc_top (
    input  wire        CLOCK_50,   // 50 MHz fabric clock (PIN_AF14)
    input  wire [3:0]  KEY,        // active-low push buttons
    input  wire [9:0]  SW,         // slide switches
    output wire [9:0]  LEDR,       // red LEDs
    output wire [6:0]  HEX0,       // seven-segment displays (active-low segments)
    output wire [6:0]  HEX1,
    output wire [6:0]  HEX2,
    output wire [6:0]  HEX3,
    output wire [6:0]  HEX4,
    output wire [6:0]  HEX5
);

  localparam int unsigned WIDTH = 8;

  logic [WIDTH-1:0] count;

  // Reference design under test. Reset is KEY[0] (active-low, matches rst_n),
  // enable is SW[0].
  counter #(
      .WIDTH(WIDTH)
  ) u_counter (
      .clk    (CLOCK_50),
      .rst_n  (KEY[0]),
      .enable (SW[0]),
      .count  (count)
  );

  // Show the raw count on the red LEDs; unused high LEDs are tied off.
  assign LEDR = {2'b00, count};

  // Simple visual aid: low nibble on HEX0, high nibble on HEX1, rest blank.
  seg7_hex u_hex0 (.nibble(count[3:0]), .seg(HEX0));
  seg7_hex u_hex1 (.nibble(count[7:4]), .seg(HEX1));

  // Cyclone V seven-segment segments are active-low; all-ones blanks a digit.
  assign HEX2 = 7'h7F;
  assign HEX3 = 7'h7F;
  assign HEX4 = 7'h7F;
  assign HEX5 = 7'h7F;

endmodule

`default_nettype wire
